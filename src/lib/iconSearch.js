// Deduplicated emoji list (H3) — the old list repeated one block 4×
// (367 entries, 122 unique). Derived from the keyword map keys.
export const ALL_ICONS = Object.keys(EMOJI_KEYWORDS)

// Pure search helper used by IconPicker.
export function searchIcons(term) {
  const q = (term || '').trim().toLowerCase()
  if (!q) return ALL_ICONS
  return ALL_ICONS.filter(emoji =>
    emoji === q || EMOJI_KEYWORDS[emoji].toLowerCase().includes(q)
  )
}
